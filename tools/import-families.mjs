#!/usr/bin/env node
// Generates PetDex/Data/FamilyData.lua from the WoW Forever client's
// CreatureFamily table (a CSV export from https://wago.tools/db2/CreatureFamily
// for a 1.60.x build).
//
// Usage: node tools/import-families.mjs <CreatureFamily.1.60.x.csv> [--out PetDex/Data/FamilyData.lua]
//
// Keeps the hunter pet families (pet skill line 270 and a diet) with their
// diet and icon.

import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const args = process.argv.slice(2);
const input = args.find((a) => !a.startsWith("--") && args[args.indexOf(a) - 1] !== "--out");
const outIndex = args.indexOf("--out");
const output = outIndex >= 0 ? args[outIndex + 1] : "PetDex/Data/FamilyData.lua";
if (!input) {
  console.error("Usage: node tools/import-families.mjs <CreatureFamily.csv> [--out file]");
  process.exit(1);
}

// PetFoodMask bits, in the order the game uses.
const FOODS = ["Meat", "Fish", "Cheese", "Bread", "Fungus", "Fruit", "Raw Meat", "Raw Fish"];
const PET_SKILL_LINE = "270";

// Minimal CSV: quoted fields with "" escapes.
function parseCSV(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const header = rows.shift();
  return rows.map((r) => Object.fromEntries(header.map((h, k) => [h, r[k]])));
}

const families = parseCSV(readFileSync(input, "utf8"))
  .filter((f) => f.SkillLine_1 === PET_SKILL_LINE && Number(f.PetFoodMask) > 0)
  .sort((a, b) => a.Name_lang.localeCompare(b.Name_lang));

const lua = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
const out = [];
out.push(`-- GENERATED by tools/import-families.mjs from the WoW Forever client's
-- CreatureFamily table (${basename(input)}). Do not edit by hand.
--
-- ns.FamilyData[name] = { id, diet = { foods }, icon = fileID, skillLine }
local _, ns = ...

ns.FamilyData = {`);
for (const f of families) {
  const mask = Number(f.PetFoodMask);
  const diet = FOODS.filter((_, bit) => mask & (1 << bit));
  out.push(`    [${lua(f.Name_lang)}] = { id = ${f.ID}, diet = { ${diet.map(lua).join(", ")} }, icon = ${f.IconFileID}, skillLine = ${f.SkillLine_0} },`);
}
out.push("}", "");
writeFileSync(output, out.join("\n"));
console.error(`wrote ${families.length} families to ${output}: ${families.map((f) => f.Name_lang).join(", ")}`);
