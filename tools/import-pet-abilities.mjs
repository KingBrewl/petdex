#!/usr/bin/env node
// Generates PetDex/Data/PetSpells.lua: the abilities each beast teaches when
// tamed, as spell sets (classic-db's PetSpellDataId on each beast points at
// one).
//
// Sources, read from Blizzard's CDN (public game data):
// - CreatureSpellData from the Classic Era client (wow_classic_era); the
//   WoW Forever client doesn't ship this table, and Forever's beast
//   training comes from Classic.
// - SkillLineAbility from the WoW Forever client (wowf): keeps only spells
//   that are pet abilities in Forever.
// - SpellName and Spell from the WoW Forever client: ability names and ranks.
//
// Usage (from tools/): npm install, then
//   node import-pet-abilities.mjs [--out ../PetDex/Data/PetSpells.lua]

import './casc-shims.mjs';
import { writeFileSync } from 'node:fs';
import { CASCClient, WDCReader, DBDParser } from '@rhyster/wow-casc-dbc';

const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const output = outIndex >= 0 ? args[outIndex + 1] : '../PetDex/Data/PetSpells.lua';

const FILES = {
  creatureSpellData: 3032554,
  skillLineAbility: 1266278,
  spellName: 1990283,
  spell: 1140089,
  creatureFamily: 1351351,
};
const PET_SKILL_LINE = 270; // abilities every hunter pet shares

async function open(product) {
  const version = await CASCClient.getProductVersion('us', product);
  const client = new CASCClient('us', product, version);
  await client.init();
  await client.loadRemoteTACTKeys();
  return { client, version };
}

async function table(client, fileDataID) {
  const keys = client.getContentKeysByFileDataID(fileDataID);
  if (!keys || !keys.length) throw new Error(`file ${fileDataID} is not in this build`);
  const key = keys.find((k) => !!(k.localeFlags & CASCClient.LocaleFlags.enUS)) ?? keys[0];
  const result = await client.getFileByContentKey(key.cKey, true);
  const parser = await DBDParser.parse(new WDCReader(result.buffer, result.blocks));
  return parser;
}

function rows(parser) {
  return parser.getAllIDs().map((id) => [id, parser.getRowData(id)]);
}

const era = await open('wow_classic_era');
const forever = await open('wowf');
console.error(`Classic Era ${era.version.VersionsName}, Forever ${forever.version.VersionsName}`);

// Pet skill lines in Forever: each hunter-pet family's, plus the shared one.
const petSkillLines = new Set([PET_SKILL_LINE]);
for (const [, family] of rows(await table(forever.client, FILES.creatureFamily))) {
  if (family.SkillLine?.[1] === PET_SKILL_LINE && family.PetFoodMask > 0) {
    petSkillLines.add(family.SkillLine[0]);
  }
}

// Spells that are pet abilities in Forever.
const petSpells = new Set();
for (const [, ability] of rows(await table(forever.client, FILES.skillLineAbility))) {
  if (petSkillLines.has(ability.SkillLine)) petSpells.add(ability.Spell);
}

const names = new Map(rows(await table(forever.client, FILES.spellName)).map(([id, r]) => [id, r.Name_lang]));
const ranks = new Map(rows(await table(forever.client, FILES.spell)).map(([id, r]) => [id, r.NameSubtext_lang]));

// Spell sets from Classic Era, keeping Forever pet abilities.
const sets = [];
let dropped = 0;
for (const [id, set] of rows(await table(era.client, FILES.creatureSpellData))) {
  const abilities = [];
  set.Spells.forEach((spellID, i) => {
    if (!spellID) return;
    if (!petSpells.has(spellID) || !names.get(spellID)) {
      dropped++;
      return;
    }
    const rank = Number(String(ranks.get(spellID) ?? '').match(/\d+/)?.[0] ?? 0);
    abilities.push({ spellID, name: names.get(spellID), rank, chance: set.Availability?.[i] ?? 100 });
  });
  if (abilities.length) sets.push({ id, abilities });
}
sets.sort((a, b) => a.id - b.id);

const lua = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const out = [];
out.push(`-- GENERATED by tools/import-pet-abilities.mjs. Do not edit by hand.
--
-- What a beast teaches when tamed, by spell set (Data/Beasts.lua's petSpells
-- field). Spell sets come from the Classic Era client's CreatureSpellData
-- (${era.version.VersionsName}); WoW Forever's client doesn't ship that table.
-- Only spells that are pet abilities in WoW Forever (${forever.version.VersionsName},
-- SkillLineAbility) are kept, named from Forever's SpellName and Spell.
-- World of Warcraft data is copyright Blizzard Entertainment.
--
-- ns.PetSpellSets[setID] = { { spell, name, rank, chance }, ... }
--   chance: percent of these beasts that know it (usually 100)
local _, ns = ...

ns.PetSpellSets = {`);
for (const set of sets) {
  const entries = set.abilities.map((a) => {
    const fields = [`spell = ${a.spellID}`, `name = ${lua(a.name)}`];
    if (a.rank) fields.push(`rank = ${a.rank}`);
    if (a.chance !== 100) fields.push(`chance = ${a.chance}`);
    return `{ ${fields.join(', ')} }`;
  });
  out.push(`    [${set.id}] = { ${entries.join(', ')} },`);
}
out.push('}', '');
writeFileSync(output, out.join('\n'));
console.error(`wrote ${sets.length} spell sets to ${output} (${petSpells.size} Forever pet abilities; ${dropped} non-pet spells dropped)`);
